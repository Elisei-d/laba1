#pragma once

#include <string>

namespace memfs {

// Единое правило корректности имени элемента ФС и сегмента пути.
// Выбрасывает InvalidNameError, если имя:
//   - пустое;
//   - содержит разделитель '/';
//   - равно "." или ".." (зарезервированы, в модели не поддерживаются).
// Свободная функция, а не метод: правило не принадлежит состоянию
// какого-либо объекта, и им пользуются и Path, и FsNode.
void validateName(const std::string& name);

}  // namespace memfs
